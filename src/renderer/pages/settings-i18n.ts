export type SettingsMessageKey = keyof (typeof SETTINGS_I18N)["en-US"];

export function resolveSettingsLocale(
  languageSetting: unknown,
  systemLanguage?: string,
): SettingsLocale {
  return resolveLocale(
    normalizeLanguageSetting(languageSetting),
    systemLanguage,
  );
}

export function formatSettingsMessage(
  locale: SettingsLocale,
  key: string,
  vars?: Record<string, string | number>,
) {
  const template =
    SETTINGS_I18N[locale][key as SettingsMessageKey] ??
    SETTINGS_I18N["en-US"][key as SettingsMessageKey] ??
    key;

  if (!vars) {
    return template;
  }

  return template.replace(/\{(\w+)\}/g, (_match, name) =>
    String(vars[name] ?? ""),
  );
}
